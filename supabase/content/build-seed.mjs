// Builds ../seed.sql from Anna's text (source.txt) and extras.mjs.
// Usage: node supabase/content/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { CHAPTERS } from "./extras.mjs";

const src = readFileSync(new URL("./source.txt", import.meta.url), "utf8").replace(/\r/g, "");
const lines = src.split("\n").map((l) => l.replace(/ /g, " ").trim());

const chapters = [];
let cur = null;
for (let i = 0; i < lines.length; i++) {
  const l = lines[i];
  const head = l.match(/^(\d{1,2})\.\s+([A-ZÆØÅ][A-ZÆØÅ ,&\-]+)$/);
  if (head && +head[1] <= 12) {
    cur = { id: +head[1], title: titleCase(head[2]), description: "", phrases: [] };
    chapters.push(cur);
    const next = lines[i + 1] || "";
    if (next && !/^\d+\./.test(next)) cur.description = next;
    continue;
  }
  if (/^13\.\s+Готові/.test(l)) break;
  const da = l.match(/^(\d+)\.\s*🇩🇰\s*(.+)$/);
  if (cur && da) {
    const ua = (lines[i + 1] || "").match(/^🇺🇦\s*(.+)$/);
    if (!ua) throw new Error("missing translation after: " + l);
    cur.phrases.push({ n: +da[1], da: da[2].trim(), ua: ua[1].trim() });
  }
}

function titleCase(s) {
  // "SYGDOM & FRAVÆR" -> "Sygdom & fravær", keep HR and E-MAIL readable
  const t = s.toLowerCase().replace(/\s+/g, " ").trim();
  return (t[0].toUpperCase() + t.slice(1)).replace(/\bhr\b/g, "HR");
}

const lib = { chapters: [], phrases: [], dialogues: [], notes: [], mistakes: [], messages: [], exercises: [], vocab: [] };
const q = (s) => (s == null ? "null" : "'" + String(s).replace(/'/g, "''") + "'");
const j = (o) => q(JSON.stringify(o)) + "::jsonb";
const out = [
  "-- Generated by supabase/content/build-seed.mjs. Do not edit by hand.",
  "begin;",
  "truncate public.chapters restart identity cascade;",
];
let total = 0;
for (const c of chapters) {
  const x = CHAPTERS[c.id];
  if (!x) throw new Error("no extras for chapter " + c.id);
  const description = c.description || x.description;
  out.push(`insert into public.chapters (id, title_da, description_ua, intro_ua) values (${c.id}, ${q(c.title)}, ${q(description)}, ${q(x.intro)});`);
  lib.chapters.push({ id: c.id, title_da: c.title, description_ua: description, intro_ua: x.intro });
  c.phrases.forEach((p) => lib.phrases.push({ id: lib.phrases.length + 1, chapter_id: c.id, sort: p.n, da: p.da, ua: p.ua, explanation_ua: x.explain[p.n] ?? null }));
  x.dialogues.forEach((d, i) => lib.dialogues.push({ id: lib.dialogues.length + 1, chapter_id: c.id, sort: i + 1, title_ua: d.title, lines: d.lines.map(([who, da, ua, me]) => ({ who, da, ua, me: !!me })) }));
  x.notes.forEach((n, i) => lib.notes.push({ id: lib.notes.length + 1, chapter_id: c.id, sort: i + 1, body_ua: n }));
  x.mistakes.forEach(([wrong, better, why_ua], i) => lib.mistakes.push({ id: lib.mistakes.length + 1, chapter_id: c.id, sort: i + 1, wrong, better, why_ua }));
  x.messages.forEach(([audience_ua, da, ua], i) => lib.messages.push({ id: lib.messages.length + 1, chapter_id: c.id, sort: i + 1, audience_ua, da, ua }));
  x.vocab.forEach(([da, ua], i) => lib.vocab.push({ id: lib.vocab.length + 1, chapter_id: c.id, sort: i + 1, da, ua }));
  for (const k of Object.keys(x.explain)) if (!c.phrases.some((p) => p.n === +k)) throw new Error(`ch${c.id}: explain for missing phrase ${k}`);
  out.push("insert into public.phrases (chapter_id, sort, da, ua, explanation_ua) values");
  out.push(c.phrases.map((p) => `(${c.id}, ${p.n}, ${q(p.da)}, ${q(p.ua)}, ${q(x.explain[p.n] ?? null)})`).join(",\n") + ";");
  total += c.phrases.length;
  x.dialogues.forEach((d, i) => out.push(`insert into public.dialogues (chapter_id, sort, title_ua, lines) values (${c.id}, ${i + 1}, ${q(d.title)}, ${j(d.lines.map(([who, da, ua, me]) => ({ who, da, ua, me: !!me })))});`));
  x.notes.forEach((n, i) => out.push(`insert into public.notes (chapter_id, sort, body_ua) values (${c.id}, ${i + 1}, ${q(n)});`));
  x.mistakes.forEach(([w, b, why], i) => out.push(`insert into public.mistakes (chapter_id, sort, wrong, better, why_ua) values (${c.id}, ${i + 1}, ${q(w)}, ${q(b)}, ${q(why)});`));
  x.messages.forEach(([a, da, ua], i) => out.push(`insert into public.messages (chapter_id, sort, audience_ua, da, ua) values (${c.id}, ${i + 1}, ${q(a)}, ${q(da)}, ${q(ua)});`));
  x.exercises.forEach((e, i) => {
    // Options are written correct-first; rotate so the right answer moves around.
    const r = (c.id + i) % e.options.length;
    const opts = e.options.map((_, k) => e.options[(k + r) % e.options.length]);
    const correct = (e.options.length - r) % e.options.length;
    lib.exercises.push({ id: lib.exercises.length + 1, chapter_id: c.id, sort: i + 1, question_ua: e.q, options: opts, correct, explain_ua: e.why ?? null });
    out.push(`insert into public.exercises (chapter_id, sort, question_ua, options, correct, explain_ua) values (${c.id}, ${i + 1}, ${q(e.q)}, ${j(opts)}, ${correct}, ${q(e.why ?? null)});`);
  });
  out.push("insert into public.vocab (chapter_id, sort, da, ua) values " + x.vocab.map(([da, ua], i) => `(${c.id}, ${i + 1}, ${q(da)}, ${q(ua)})`).join(", ") + ";");
}
// Grammar chapters 13-14: their text lives in the app (client/src/content/grammar.json);
// the rows exist so progress and admin statistics treat them like any chapter.
const grammar = JSON.parse(readFileSync(new URL("../../client/src/content/grammar.json", import.meta.url), "utf8"));
for (const g of grammar.chapters) {
  out.push(`insert into public.chapters (id, title_da, description_ua, intro_ua) values (${g.id}, ${q(g.title_da)}, ${q(g.title)}, '');`);
  lib.chapters.push({ id: g.id, title_da: g.title_da, description_ua: g.title, intro_ua: "" });
}
out.push("commit;");
// Inventory consumers can obtain the exact library without touching seed.sql.
if (!process.argv.includes("--json-only")) writeFileSync(new URL("../seed.sql", import.meta.url), out.join("\n") + "\n");
// Optional: node build-seed.mjs --json <file> writes the same content as JSON (used by UI tests).
const jsonAt = process.argv.indexOf("--json");
if (jsonAt > 0) writeFileSync(process.argv[jsonAt + 1], JSON.stringify(lib));
console.log(chapters.map((c) => `${c.id}. ${c.title} (${c.phrases.length})`).join("\n"));
console.log("phrases:", total);
